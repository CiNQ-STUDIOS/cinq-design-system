#!/usr/bin/env node
/**
 * CiNQ coverage check.
 *
 *   node tooling/coverage/check.js          verify and write COVERAGE_MATRIX.md; exit 1 on any gap
 *   node tooling/coverage/check.js --quiet  verify only
 *
 * For every item in tooling/coverage/coverage.json: every mapped file must
 * exist and at least one of them must contain the item's phrase
 * (case-insensitive). Also fails if any file in the target structure of the
 * master prompt (§4) is missing, or if any Markdown file in the repo
 * contains a placeholder (TODO, TBD, "insert here", lorem, "etc.").
 */
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "../..");
const QUIET = process.argv.includes("--quiet");
const manifest = JSON.parse(fs.readFileSync(path.join(__dirname, "coverage.json"), "utf8"));

const required = [
  "DESIGN.md", "DECISIONS.md", "AGENT_RULES.md", "COVERAGE_MATRIX.md", "MIGRATION_PLAYBOOK.md", "PROGRESS.md",
  "audit/BRAND_DNA.md", "audit/GAP_ANALYSIS.md",
  "foundations/tokens.json", "foundations/color-system.md", "foundations/gradients-and-effects.md", "foundations/typography.md",
  "foundations/elevation-depth.md", "foundations/motion.md", "foundations/transitions-and-choreography.md",
  "foundations/iconography-imagery.md", "foundations/accessibility.md", "foundations/content-voice.md",
  "foundations/sound-and-haptics.md", "foundations/theming-and-whitelabel.md",
  "layout-architecture/grid-and-spacing.md", "layout-architecture/anti-bento-grammar.md", "layout-architecture/archetypes.md", "layout-architecture/screen-inventory.md",
  "components/global-states.md", "components/core-primitives.md", "components/form-controls-advanced.md", "components/navigation.md",
  "components/data-surfaces.md", "components/data-visualization.md", "components/overlays-feedback.md",
  "patterns/onboarding-flows.md", "patterns/forms-and-validation.md", "patterns/search-and-command.md", "patterns/realtime-and-offline.md",
  "patterns/auth-and-permissions.md", "patterns/documents-and-print.md",
  "platforms/web-and-dashboards.md", "platforms/mobile-apps.md", "platforms/tablet-kiosk-pos.md", "platforms/marketing-and-demos.md",
  "implementations/variables.css", "implementations/tailwind.config.ts", "implementations/react_tokens.ts", "implementations/flutter_theme.dart", "implementations/motion.css",
  "tooling/lint/eslint.config.mjs", "tooling/lint/stylelint.config.cjs", "tooling/audit-script/audit.js", "tooling/contrast-check/check.js", "tooling/motion-check/check.js",
  "governance/VERSIONING.md", "governance/CONTRIBUTING.md", "governance/TESTING.md",
  "showcase/index.html", "showcase/motion-lab.html", "showcase/gradient-lab.html",
  "showcase/archetypes/operational-console.html", "showcase/archetypes/executive-dashboard.html", "showcase/archetypes/data-workspace.html",
  "showcase/archetypes/setup-onboarding.html", "showcase/archetypes/detail-record.html", "showcase/archetypes/mobile-utility.html",
  "showcase/archetypes/tablet-kiosk-pos.html", "showcase/archetypes/settings.html", "showcase/archetypes/auth-entry.html", "showcase/archetypes/rms-after.html",
];

const fails = [];
const rows = [];
for (const it of manifest.items) {
  const missing = it.files.filter((f) => !fs.existsSync(path.join(ROOT, f)));
  const found = it.files.some((f) => fs.existsSync(path.join(ROOT, f)) && fs.readFileSync(path.join(ROOT, f), "utf8").toLowerCase().includes(it.grep.toLowerCase()));
  let status = "covered";
  if (missing.length) { status = `missing: ${missing.join(", ")}`; fails.push(`${it.item}: ${status}`); }
  else if (!found) { status = `phrase "${it.grep}" not found`; fails.push(`${it.item}: ${status}`); }
  rows.push({ item: it.item, files: it.files, status });
}
for (const f of required) {
  if (f === "COVERAGE_MATRIX.md" && !QUIET) continue; // written by this run
  if (!fs.existsSync(path.join(ROOT, f))) fails.push(`required file missing: ${f}`);
}

// placeholders
const PLACEHOLDER = /\b(TODO|TBD|FIXME|lorem ipsum|insert here|coming soon)\b|\betc\.|\[placeholder\]/i;
(function walk(d) {
  for (const e of fs.readdirSync(d, { withFileTypes: true })) {
    const p = path.join(d, e.name);
    if (/node_modules|\.git|tooling[\\/]coverage|profiles|project-profile|CHANGELOG|README|prompts/.test(p)) continue;
    if (e.isDirectory()) walk(p);
    else if (/\.(md|html|css|ts|tsx|js|dart)$/.test(e.name)) {
      const text = fs.readFileSync(p, "utf8");
      const m = text.match(PLACEHOLDER);
      if (m) fails.push(`placeholder "${m[0]}" in ${path.relative(ROOT, p)}`);
    }
  }
})(ROOT);

if (!QUIET) {
  let md = `# Coverage matrix\n\nGENERATED by \`tooling/coverage/check.js\` from \`tooling/coverage/coverage.json\`. ${rows.length} items. Result: ${fails.length === 0 ? "**every item mapped and present**" : `**${fails.length} gaps**`}.\n\n| Item | Specified in | Status |\n|:--|:--|:--|\n`;
  for (const r of rows) md += `| ${r.item} | ${r.files.map((f) => `\`${f}\``).join(", ")} | ${r.status === "covered" ? "covered" : `**${r.status}**`} |\n`;
  md += `\n## Required files (master prompt §4)\n\n${required.length} files required; ${required.filter((f) => fs.existsSync(path.join(ROOT, f))).length} present.\n`;
  fs.writeFileSync(path.join(ROOT, "COVERAGE_MATRIX.md"), md);
}

console.log(`coverage: ${rows.length} items · ${required.length} required files · ${fails.length} gaps`);
if (fails.length) {
  for (const f of fails) console.error("  " + f);
  process.exit(1);
}
